#!/usr/bin/env python3
"""Generates assets/kit/programs.js (the program list of the shared kit) from public-release.json.

  python tools/kit_programs.py            check: exit 1 if programs.js is not what the generator would write
  python tools/kit_programs.py --write    rewrite programs.js

Source of truth: projects[] (name, platform, description) and the top-level dictionaries
catalog_icons, catalog_categories, catalog_stacks, catalog_websites. No versions are written,
so the 19 site copies do not go stale with every release.
"""
import argparse
import json
import pathlib
import sys

DEFAULT_ROOT = pathlib.Path(__file__).resolve().parents[1]
SITE = 'https://popovantondev.github.io/popovantondev/'
LANGS = ('de', 'en', 'ru')
CATALOG = {'de': SITE + 'index.html', 'en': SITE + 'index-en.html', 'ru': SITE + 'index-ru.html'}
CATEGORIES = {
    'lernen': {'de': 'Lernen', 'en': 'Learning', 'ru': 'Учёба'},
    'medien': {'de': 'Medien', 'en': 'Media', 'ru': 'Медиа'},
    'werkzeuge': {'de': 'Werkzeuge', 'en': 'Tools', 'ru': 'Инструменты'},
    'daten': {'de': 'Daten & Backup', 'en': 'Data & backup', 'ru': 'Данные и бэкап'},
}
HEADER = '/* Generated by tools/kit_programs.py from public-release.json. Do not edit by hand. */\n'


def dumps(value):
    return json.dumps(value, ensure_ascii=False)


def build(data):
    """Returns (programs.js text, list of problems)."""
    errors = []
    items = []
    for p in data['projects']:
        repo = p['repo']
        category = data.get('catalog_categories', {}).get(repo)
        if category not in CATEGORIES:
            errors.append('%s: catalog_categories must be one of %s (got %r)' % (repo, '/'.join(CATEGORIES), category))
        stack = data.get('catalog_stacks', {}).get(repo, '')
        if not stack.strip():
            errors.append('%s: catalog_stacks is missing' % repo)
        icon = data.get('catalog_icons', {}).get(repo)
        if not icon:
            errors.append('%s: catalog_icons is missing' % repo)
        sites = data.get('catalog_websites', {}).get(repo, {})
        if sorted(sites) != sorted(LANGS):
            errors.append('%s: catalog_websites needs de/en/ru' % repo)
        items.append({
            'repo': repo, 'name': p['name'], 'icon': SITE + (icon or ''),
            'category': category, 'stack': stack, 'platform': p['platform'],
            'url': {l: sites.get(l, '') for l in LANGS},
            'desc': {l: p['description'][l] for l in LANGS},
        })
    lines = [HEADER, 'window.PPK_PROGRAMS = [\n', ',\n'.join(dumps(i) for i in items), '\n];\n',
             'window.PPK_CATALOG = %s;\n' % dumps(CATALOG),
             'window.PPK_CATEGORIES = %s;\n' % dumps(CATEGORIES)]
    return ''.join(lines), errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write', action='store_true', help='rewrite assets/kit/programs.js')
    parser.add_argument('--root', type=pathlib.Path, default=DEFAULT_ROOT, help='profile repository root')
    args = parser.parse_args(argv)
    data = json.loads((args.root / 'public-release.json').read_text(encoding='utf-8'))
    text, errors = build(data)
    if errors:
        print('\n'.join(errors))
        return 1
    target = args.root / 'assets' / 'kit' / 'programs.js'
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('programs.js written: %d programs' % len(data['projects']))
        return 0
    current = target.read_bytes().decode('utf-8') if target.is_file() else None
    if current != text:
        print('assets/kit/programs.js is out of date. Fix: python tools/kit_programs.py --write')
        return 1
    print('programs.js is current: %d programs' % len(data['projects']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
